/**
 * VESTARA Extractor — export library (Phase 3).
 *
 * Format transforms, barrel-file generation, and ZIP packaging.
 * Transforms are best-effort previews (labelled as such in the UI) —
 * review generated code before shipping it.
 */

import JSZip from 'jszip';
import type { ExtractedComponent } from './types.js';

export type ExportFormat = 'react' | 'typescript' | 'vue' | 'plain';

export interface ExportFormatOption {
  readonly id: ExportFormat;
  readonly label: string;
}

export const EXPORT_FORMATS: readonly ExportFormatOption[] = [
  { id: 'typescript', label: 'TypeScript' },
  { id: 'react', label: 'React' },
  { id: 'vue', label: 'Vue' },
  { id: 'plain', label: 'Plain JSX' },
];

export const DEFAULT_EXPORT_FORMAT: ExportFormat = 'typescript';

export const NPM_INSTALL_COMMAND = 'npm install ./vestara-ui-extract.zip';

function extFor(format: ExportFormat): string {
  switch (format) {
    case 'vue':
      return '.vue';
    case 'react':
    case 'plain':
      return '.jsx';
    case 'typescript':
    default:
      return '.tsx';
  }
}

export function fileNameFor(component: ExtractedComponent, format: ExportFormat): string {
  return component.file.replace(/\.tsx$/, extFor(format));
}

function propsTypeBlock(component: ExtractedComponent): string {
  const lines = component.props.map((p) => `  ${p.name}: ${p.type};`);
  return `export type ${component.name}Props = {\n${lines.join('\n')}\n};`;
}

/** Render one component's clean source in the target format. */
export function renderClean(component: ExtractedComponent, format: ExportFormat): string {
  const base = component.source.clean;
  switch (format) {
    case 'typescript':
      return `${base}\n\n${propsTypeBlock(component)}\n`;
    case 'vue':
      return [
        `<script setup>`,
        `// ${component.name} — converted preview from the React artifact. Review before shipping.`,
        `const props = defineProps(${JSON.stringify(component.props.map((p) => p.name))});`,
        `</script>`,
        `<template>`,
        `  <div><!-- ${component.name} -->`,
        `    <slot />`,
        `  </div>`,
        `</template>`,
        ``,
      ].join('\n');
    default:
      return base.endsWith('\n') ? base : `${base}\n`;
  }
}

/** Barrel entry point re-exporting every component. */
export function buildBarrel(components: readonly ExtractedComponent[], format: ExportFormat): string {
  const lines = components.map((c) => `export { default as ${c.name} } from './components/${fileNameFor(c, format)}';`);
  return [
    `// Generated by VESTARA Extractor — ${format} barrel. Review before shipping.`,
    ...lines,
    ``,
  ].join('\n');
}

function packageJson(): string {
  return `${JSON.stringify({ name: 'vestara-ui-extract', version: '1.0.0', main: 'index.js' }, null, 2)}\n`;
}

export interface ZipFile {
  readonly path: string;
  readonly content: string;
}

/** Full file list for the distributable ZIP. */
export function buildFileList(
  components: readonly ExtractedComponent[],
  format: ExportFormat,
  tokensCss: string,
  manifestJson: string,
  includeTokens: boolean,
): readonly ZipFile[] {
  const files: ZipFile[] = components.map((c) => ({
    path: `components/${fileNameFor(c, format)}`,
    content: renderClean(c, format),
  }));
  files.push({ path: 'index.js', content: buildBarrel(components, format) });
  files.push({ path: 'manifest.json', content: manifestJson });
  files.push({ path: 'package.json', content: packageJson() });
  if (includeTokens) files.push({ path: 'tokens.css', content: tokensCss });
  files.push({
    path: 'README.txt',
    content: [
      'VESTARA Extractor output.',
      `Format: ${format}. Components: ${components.length}.`,
      'Generated as a best-effort preview — review before shipping.',
    ].join('\n'),
  });
  return files;
}

/** Package files as a ZIP archive (stored download). */
export async function buildZip(files: readonly ZipFile[]): Promise<Uint8Array> {
  const zip = new JSZip();
  for (const file of files) zip.file(file.path, file.content);
  return zip.generateAsync({ type: 'uint8array', compression: 'DEFLATE' });
}

/** Trigger a browser download for a Blob. */
export function downloadBlob(filename: string, blob: Blob): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
